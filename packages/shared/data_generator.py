"""Tagged Synthetic Test Data Generator and Cleanup Identifier.

Implements Pillar 4: All synthetic test data generated by AutoQA uses consistent
identifying prefixes and run tags (format: AUTOQA_{run_id}_{field}_{unique} or
autoqa_{run_id}_{hash}@testqa.local), enabling deterministic recognition, validation
compliance, and automated database teardown.
"""

import re
import uuid
import random
from typing import Optional, Dict, Any


TAG_PREFIX = "AUTOQA"
EMAIL_DOMAIN = "testqa.local"


class SyntheticDataGenerator:
    """Generates realistic, typed synthetic data with AutoQA tracking tags."""

    def __init__(self, run_id: str):
        self.run_id = self._sanitize_tag(run_id or "run")

    @staticmethod
    def _sanitize_tag(val: str) -> str:
        """Sanitizes run_id or field name for alphanumeric tag safety."""
        clean = re.sub(r"[^a-zA-Z0-9_]", "_", str(val))
        return clean[:24].strip("_") or "run"

    def _rand_hash(self, length: int = 8) -> str:
        return uuid.uuid4().hex[:length]

    def generate(self, field_name: str, field_type: str = "text", constraints: Optional[Dict[str, Any]] = None) -> str:
        """Generates appropriate synthetic value conforming to field type and constraints."""
        f_type = (field_type or "text").lower()
        f_name = (field_name or "field").lower()
        constraints = constraints or {}

        # Heuristic detection from field name if type is generic text
        if f_type in ("text", "string", ""):
            if any(k in f_name for k in ("email", "mail")):
                f_type = "email"
            elif any(k in f_name for k in ("password", "pass", "pwd", "secret")):
                f_type = "password"
            elif any(k in f_name for k in ("phone", "tel", "mobile")):
                f_type = "phone"
            elif any(k in f_name for k in ("username", "user_name", "login")):
                # Generate tagged text representation
                f_type = "text"
            elif any(k in f_name for k in ("age", "qty", "quantity", "count", "num")):
                f_type = "number"
            elif any(k in f_name for k in ("price", "amount", "total", "cost")):
                f_type = "currency"
            elif any(k in f_name for k in ("date", "birthday", "dob")):
                f_type = "date"
            elif any(k in f_name for k in ("url", "website", "link")):
                f_type = "url"

        if f_type == "email":
            return self.email()
        elif f_type == "password":
            return self.password()
        elif f_type == "phone":
            return self.phone()
        elif f_type in ("number", "integer", "int"):
            min_val = constraints.get("min", 1)
            max_val = constraints.get("max", 100)
            return str(random.randint(min_val, max_val))
        elif f_type in ("currency", "float", "decimal"):
            return f"{random.uniform(10.0, 500.0):.2f}"
        elif f_type == "date":
            year = random.randint(1990, 2005)
            month = random.randint(1, 12)
            day = random.randint(1, 28)
            return f"{year:04d}-{month:02d}-{day:02d}"
        elif f_type == "url":
            return f"https://{self._rand_hash(6)}.example.com"

        # Standard tagged text: AUTOQA_<run_id>_<field>_<hash>
        safe_field = self._sanitize_tag(field_name)
        val = f"{TAG_PREFIX}_{self.run_id}_{safe_field}_{self._rand_hash(6)}"
        max_len = constraints.get("max_length")
        if max_len and len(val) > max_len:
            val = val[:max_len]
        return val

    def email(self) -> str:
        """Generates a valid email with run_id tracking: autoqa_{run_id}_{hash}@testqa.local."""
        return f"autoqa_{self.run_id}_{self._rand_hash(8)}@{EMAIL_DOMAIN}".lower()

    def username(self) -> str:
        """Generates a valid tagged username: AUTOQA_{run_id}_user_{hash}."""
        return f"{TAG_PREFIX}_{self.run_id}_user_{self._rand_hash(6)}"

    def password(self) -> str:
        """Generates a strong password meeting standard security policies."""
        return f"AutoQA!{self._rand_hash(6).capitalize()}1#"

    def phone(self) -> str:
        """Generates a valid phone number format: +84901XXXXXX."""
        suffix = "".join(str(random.randint(0, 9)) for _ in range(6))
        return f"+84901{suffix}"


def is_tagged_test_data(value: str, run_id: Optional[str] = None) -> bool:
    """Checks whether a string value was generated by AutoQA synthetic data engine.
    
    If run_id is supplied, verifies whether the value belongs to that specific run.
    """
    if not isinstance(value, str):
        return False

    v_str = value.strip()
    if not v_str:
        return False

    if run_id:
        clean_run = SyntheticDataGenerator._sanitize_tag(run_id)
        return (
            v_str.startswith(f"{TAG_PREFIX}_{clean_run}_")
            or v_str.lower().startswith(f"autoqa_{clean_run.lower()}_")
        )

    return (
        v_str.startswith(f"{TAG_PREFIX}_")
        or v_str.lower().startswith("autoqa_")
    )


def extract_test_run_id(value: str) -> Optional[str]:
    """Extracts the run_id from an AutoQA tagged value if present."""
    if not isinstance(value, str):
        return None

    v_str = value.strip()

    # Case 1: email -> autoqa_<run_id>_<hash>@testqa.local
    if v_str.lower().endswith(f"@{EMAIL_DOMAIN}") and v_str.lower().startswith("autoqa_"):
        prefix = v_str[:-len(f"@{EMAIL_DOMAIN}")]
        # Remove 'autoqa_' prefix and last '_<hash>'
        sub = prefix[len("autoqa_"):]
        last_underscore = sub.rfind("_")
        if last_underscore > 0:
            return sub[:last_underscore]
        return sub

    # Case 2: standard tag -> AUTOQA_<run_id>_<field>_<hash>
    if v_str.upper().startswith(f"{TAG_PREFIX}_"):
        sub = v_str[len(f"{TAG_PREFIX}_"):]
        tokens = sub.split("_")
        if len(tokens) >= 2:
            if tokens[0].lower() == "run" and len(tokens) >= 3:
                return f"run_{tokens[1]}"
            return tokens[0]

    return None
